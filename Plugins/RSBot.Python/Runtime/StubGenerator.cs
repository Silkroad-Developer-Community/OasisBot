using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using Python.Runtime;
using RSBot.Python.API;
using RSBot.Python.API.GUI;

namespace RSBot.Python.Runtime
{
    public static class PythonStubGenerator
    {
        public static void Generate(IEnumerable<IPythonPlugin> modules, string path)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Auto-generated by OasisBot.Python. Do not edit manually.");
            sb.AppendLine($"# Generated: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine("from typing import Any, Optional, Callable, overload");
            sb.AppendLine();

            WriteGuiClasses(sb);

            var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var module in modules.OrderBy(x => x.ModuleName))
            {
                sb.AppendLine($"# {module.ModuleName}");
                foreach (var method in module.GetType().GetMethods(BindingFlags.Instance | BindingFlags.Public))
                {
                    if (
                        method.DeclaringType == typeof(object)
                        || method.IsSpecialName
                        || method.Name == nameof(IPythonPlugin.Init)
                        || !names.Add(method.Name)
                    )
                        continue;

                    var parameters = FormatParameters(method);
                    sb.AppendLine($"def {method.Name}({parameters}) -> {MapType(method.ReturnType)}: ...");
                }
                sb.AppendLine();
            }

            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, sb.ToString(), Encoding.UTF8);
        }

        private static void WriteGuiClasses(StringBuilder sb)
        {
            sb.AppendLine("# --- GUI Classes ---");
            sb.AppendLine();

            WriteClass(sb, typeof(GuiControlWrapper), null);

            var wrapperTypes = typeof(GuiControlWrapper)
                .Assembly.GetTypes()
                .Where(t =>
                    typeof(GuiControlWrapper).IsAssignableFrom(t)
                    && t != typeof(GuiControlWrapper)
                    && !t.IsAbstract
                    && t.IsClass
                )
                .OrderBy(t => t.Name);

            foreach (var type in wrapperTypes)
            {
                WriteClass(sb, type, typeof(GuiControlWrapper).Name);
            }

            WriteClass(sb, typeof(PythonGui), null);
        }

        private static void WriteClass(StringBuilder sb, Type type, string baseClassName)
        {
            var classHeader = baseClassName != null ? $"class {type.Name}({baseClassName}):" : $"class {type.Name}:";

            var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                .Where(p => !p.IsSpecialName)
                .OrderBy(p => p.Name)
                .ToArray();

            var methods = type.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                .Where(m => !m.IsSpecialName && !IsIgnoredMethod(m))
                .OrderBy(m => m.Name)
                .ToArray();

            if (properties.Length == 0 && methods.Length == 0)
            {
                sb.AppendLine(
                    baseClassName != null ? $"class {type.Name}({baseClassName}): ..." : $"class {type.Name}: ..."
                );
                sb.AppendLine();
                return;
            }

            sb.AppendLine(classHeader);

            foreach (var prop in properties)
            {
                sb.AppendLine($"    {prop.Name}: {MapType(prop.PropertyType)}");
            }

            var methodGroups = methods.GroupBy(m => m.Name);
            foreach (var group in methodGroups)
            {
                var list = group.ToList();
                var seenSignatures = new HashSet<string>();
                var uniqueMethods = new List<string>();

                foreach (var m in list)
                {
                    var paramList = FormatParameters(m);
                    var returnType = MapType(m.ReturnType);
                    var sig =
                        $"def {m.Name}(self{(paramList.Length > 0 ? ", " + paramList : "")}) -> {returnType}: ...";
                    if (seenSignatures.Add(sig))
                    {
                        uniqueMethods.Add(sig);
                    }
                }

                bool isOverloaded = uniqueMethods.Count > 1;
                foreach (var sig in uniqueMethods)
                {
                    if (isOverloaded)
                        sb.AppendLine("    @overload");
                    sb.AppendLine($"    {sig}");
                }
            }

            sb.AppendLine();
        }

        private static bool IsIgnoredMethod(MethodInfo method)
        {
            if (method.DeclaringType == typeof(object))
                return true;

            if (method.Name is "Dispose" or "ToString" or "Equals" or "GetHashCode" or "GetType")
                return true;

            return false;
        }

        private static string FormatParameters(MethodInfo method)
        {
            var parameters = method
                .GetParameters()
                .Select(p =>
                {
                    var annotation = MapType(p.ParameterType);
                    var optional = p.HasDefaultValue ? $" = {FormatDefault(p.DefaultValue)}" : string.Empty;
                    return $"{p.Name}: {annotation}{optional}";
                });

            return string.Join(", ", parameters);
        }

        private static string MapType(Type type)
        {
            type = Nullable.GetUnderlyingType(type) ?? type;
            if (type == typeof(void))
                return "None";
            if (type == typeof(string) || type == typeof(char))
                return "str";
            if (type == typeof(bool))
                return "bool";
            if (
                type == typeof(byte)
                || type == typeof(sbyte)
                || type == typeof(short)
                || type == typeof(ushort)
                || type == typeof(int)
                || type == typeof(uint)
                || type == typeof(long)
                || type == typeof(ulong)
            )
                return "int";
            if (type == typeof(float) || type == typeof(double) || type == typeof(decimal))
                return "float";
            if (type == typeof(byte[]))
                return "bytes";
            if (type == typeof(PyDict))
                return "dict[str, Any]";
            if (type == typeof(PyList))
                return "list[Any]";
            if (type == typeof(PythonGui))
                return "PythonGui";
            if (typeof(GuiControlWrapper).IsAssignableFrom(type))
                return type.Name;
            if (typeof(IDictionary).IsAssignableFrom(type))
                return "dict[str, Any]";
            if (type != typeof(string) && typeof(IEnumerable).IsAssignableFrom(type))
                return "list[Any]";
            if (typeof(PyObject).IsAssignableFrom(type))
                return "Any";
            return "Any";
        }

        private static string FormatDefault(object value)
        {
            if (value == null)
                return "None";
            if (value is bool b)
                return b ? "True" : "False";
            if (value is string s)
                return $"\"{s.Replace("\"", "\\\"")}\"";
            return Convert.ToString(value, CultureInfo.InvariantCulture) ?? "None";
        }
    }
}
